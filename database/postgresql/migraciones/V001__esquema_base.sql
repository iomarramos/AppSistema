  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id BIGINT NOT NULL,
  codigo TEXT NOT NULL,
  nombre TEXT NOT NULL,
  identificacion_fiscal TEXT,
