CREATE INDEX ix_receta_version_empresa ON receta_version(empresa_id);

CREATE TABLE receta_ingrediente (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id BIGINT NOT NULL,
  receta_version_id BIGINT NOT NULL,
  producto_base_id BIGINT NOT NULL,
  cantidad_base_bruta_u6 BIGINT NOT NULL CHECK(cantidad_base_bruta_u6>0),
  cantidad_base_neta_u6 BIGINT CHECK(cantidad_base_neta_u6>=0),
  orden BIGINT NOT NULL DEFAULT 1,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(empresa_id,id),
  FOREIGN KEY(empresa_id) REFERENCES empresa(id),
  FOREIGN KEY(empresa_id,receta_version_id) REFERENCES receta_version(empresa_id,id),
