SELECT rp.empresa_id, rp.rol_id, nuevo.id
FROM rol_permiso rp
JOIN permiso ma ON ma.empresa_id = rp.empresa_id AND ma.id = rp.permiso_id AND ma.codigo = 'MINUTAS_APROBAR'
JOIN permiso nuevo ON nuevo.empresa_id = rp.empresa_id AND nuevo.codigo = 'FACTORES_EDITAR'
ON CONFLICT (empresa_id, rol_id, permiso_id) DO NOTHING;
